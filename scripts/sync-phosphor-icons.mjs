#!/usr/bin/env node
/** Generate the offline UI sprite from pinned, unmodified Phosphor sources. */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceDir = path.join(root, 'icons/phosphor');
const manifest = JSON.parse(await readFile(path.join(sourceDir, 'source.json'), 'utf8'));
const check = process.argv.includes('--check');
const sources = new Map();

// Fail before writing if a vendored source differs from the recorded upstream bytes.
for (const [upstreamPath, expectedHash] of Object.entries(manifest.files)) {
  const localPath = upstreamPath.replace(/^assets\//, '');
  const data = await readFile(path.join(sourceDir, localPath));
  const hash = createHash('sha256').update(data).digest('hex');
  if (hash !== expectedHash) throw new Error(`Phosphor source checksum mismatch: ${localPath}`);
  sources.set(upstreamPath, data.toString('utf8'));
}

const license = sources.get('LICENSE').trimEnd();
const notice = `<!--
Phosphor Icons (${manifest.package} ${manifest.version}, ${manifest.weight})
Source: ${manifest.repository}/tree/${manifest.commit}
Generated by scripts/sync-phosphor-icons.mjs; do not edit geometry here.
SVG wrappers are adapted for this app; upstream path data is unchanged.

${license}
-->`;

const glyphs = new Map();
for (const [upstreamPath, svg] of sources) {
  if (upstreamPath === 'LICENSE') continue;
  const match = svg.trim().match(/^<svg\b[^>]*viewBox="(0 0 256 256)"[^>]*>([\s\S]+)<\/svg>$/);
  if (!match) throw new Error(`Unexpected Phosphor SVG: ${upstreamPath}`);
  glyphs.set(path.basename(upstreamPath, '.svg'), match[2]);
}

const symbols = [...glyphs].map(([name, body]) =>
  `  <symbol id="ph-${name}" viewBox="0 0 256 256">${body}</symbol>`
).join('\n');
const outputs = new Map([
  ['icons/phosphor-sprite.svg', `${notice}\n<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor" stroke="none">\n${symbols}\n</svg>\n`]
]);

// CSS background images cannot inherit currentColor from their select element.
for (const [theme, color] of [['light', '#5A5E66'], ['dark', '#8B96AC']]) {
  outputs.set(`icons/phosphor-caret-down-${theme}.svg`, `${notice}\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="${color}">${glyphs.get('caret-down')}</svg>\n`);
}

// CSS masks replace decorative font symbols while inheriting the element color.
for (const name of ['caret-right', 'warning-circle']) {
  outputs.set(`icons/phosphor-${name}.svg`, `${notice}\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor">${glyphs.get(name)}</svg>\n`);
}

for (const [relativePath, content] of outputs) {
  const target = path.join(root, relativePath);
  if (check) {
    const actual = await readFile(target, 'utf8');
    if (actual !== content) throw new Error(`Stale ${relativePath}; run npm run icons:sync`);
  } else {
    await writeFile(target, content);
  }
}
console.log(`${check ? 'Verified' : 'Generated'} ${glyphs.size} Phosphor glyphs, source checksums, license, sprite, select carets, and masks.`);
