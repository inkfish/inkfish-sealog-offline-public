#!/usr/bin/env node
/** Generate generic app icons from the pinned, unmodified Phosphor list glyph. */
import { createHash } from 'node:crypto';
import { chmod, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { chromium } from '@playwright/test';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceDir = path.join(root, 'icons/phosphor');
const manifest = JSON.parse(await readFile(path.join(sourceDir, 'source.json'), 'utf8'));
const check = process.argv.includes('--check');
const sources = new Map();
for (const upstreamPath of ['assets/regular/list.svg', 'LICENSE']) {
  const data = await readFile(path.join(sourceDir, upstreamPath.replace(/^assets\//, '')));
  if (createHash('sha256').update(data).digest('hex') !== manifest.files[upstreamPath]) {
    throw new Error(`Phosphor source checksum mismatch: ${upstreamPath}`);
  }
  sources.set(upstreamPath, data.toString('utf8'));
}
const match = sources.get('assets/regular/list.svg').trim()
  .match(/^<svg\b[^>]*viewBox="0 0 256 256"[^>]*>([\s\S]+)<\/svg>$/);
if (!match) throw new Error('Unexpected Phosphor list SVG');
const svg = `<!--
Phosphor Icons (${manifest.package} ${manifest.version}, ${manifest.weight})
Source: ${manifest.repository}/blob/${manifest.commit}/assets/regular/list.svg
Generated by scripts/sync-app-icons.mjs; upstream list path data is unchanged.
The teal background and white fill are this app's wrapper.

${sources.get('LICENSE').trimEnd()}
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="#ffffff">
  <rect width="256" height="256" fill="#0f766e"/>
  ${match[1]}
</svg>
`;
const outputs = new Map([['icons/app-icon.svg', Buffer.from(svg)]]);
const pngs = new Map();
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  for (const size of [16, 32, 48, 180, 192, 512]) {
    await page.setViewportSize({ width: size, height: size });
    await page.setContent(`<style>html,body{margin:0}svg{display:block;width:100vw;height:100vh}</style>${svg}`);
    pngs.set(size, await page.screenshot({ type: 'png', scale: 'css' }));
  }
} finally {
  await browser.close();
}
for (const [name, size] of [
  ['favicon-16x16', 16], ['favicon-32x32', 32],
  ['apple-touch-icon', 180],
  ['icon-192', 192], ['icon-512', 512]
]) outputs.set(`icons/${name}.png`, pngs.get(size));

const icoSizes = [16, 32, 48];
const header = Buffer.alloc(6 + 16 * icoSizes.length);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(icoSizes.length, 4);
let offset = header.length;
icoSizes.forEach((size, index) => {
  const entry = 6 + 16 * index;
  header[entry] = header[entry + 1] = size;
  header.writeUInt16LE(1, entry + 4);
  header.writeUInt16LE(32, entry + 6);
  header.writeUInt32LE(pngs.get(size).length, entry + 8);
  header.writeUInt32LE(offset, entry + 12);
  offset += pngs.get(size).length;
});
outputs.set('favicon.ico', Buffer.concat([header, ...icoSizes.map((size) => pngs.get(size))]));
for (const [relativePath, content] of outputs) {
  const target = path.join(root, relativePath);
  if (check) {
    if (!(await readFile(target)).equals(content)) throw new Error(`Stale ${relativePath}; run node scripts/sync-app-icons.mjs`);
  } else {
    await writeFile(target, content);
    await chmod(target, 0o644);
  }
}
console.log(`${check ? 'Verified' : 'Generated'} app SVG, five PNG icons, and three-size favicon with pinned Phosphor provenance.`);
